#!/usr/bin/env node
/* Collect every non-ASCII character used by src/i18n/zh.lua plus printable ASCII.
 * Outputs a pyftsubset --text-file and a Lua table the tests use to guarantee
 * that a shipped font subset covers the current translation table. */
const fs = require('fs');

const [src, charsOut, luaOut] = process.argv.slice(2);
if (!src || !charsOut || !luaOut) {
  console.error('usage: extract_i18n_chars.js <zh.lua> <chars.txt> <cjk_glyphs.lua>');
  process.exit(2);
}

const text = fs.readFileSync(src, 'utf8');
const set = new Set();
for (const ch of text) {
  if (ch.codePointAt(0) > 0x7f) set.add(ch);
}
for (let c = 0x20; c <= 0x7e; c += 1) set.add(String.fromCodePoint(c));

const chars = [...set]
  .sort((a, b) => a.codePointAt(0) - b.codePointAt(0))
  .join('');

fs.writeFileSync(charsOut, chars + '\n');
fs.writeFileSync(luaOut,
  '-- GENERATED by tools/gen_cjk_font.sh -- do not edit by hand.\n' +
  '-- Every non-ASCII character used by src/i18n/zh.lua. The shipped\n' +
  '-- assets/fonts/shiftline-cjk.ttf covers exactly this set.\n' +
  'return { chars = [==[' + chars + ']==] }\n');
console.log('[fonts] ' + set.size + ' characters -> ' + charsOut);
