function buildSheet(tiles, tileW, tileH, cols) {
  const rows = Math.ceil(tiles.length / cols);
  const cv = new Canvas(cols * tileW, rows * tileH);
  tiles.forEach((t, i) => {
    if (t.rows.length !== tileH || t.rows.some((row) => row.length !== tileW)) {
      throw new Error(`invalid ${t.key} sprite dimensions`);
    }
    const tx = (i % cols) * tileW;
    const ty = Math.floor(i / cols) * tileH;
    cv.mask(tx, ty, t.rows, [255, 255, 255], 255);
  });
  return { canvas: cv, cols, rows };
}

