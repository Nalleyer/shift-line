const FONT_CHARS = Object.keys(G).join('');
const FONT_COLS = 8;
const CELL_W = 6; // 5px glyph + 1px tracking
const CELL_H = 8; // 7px glyph + 1px leading

function buildFont() {
  const rows = Math.ceil(FONT_CHARS.length / FONT_COLS);
  const cv = new Canvas(FONT_COLS * CELL_W, rows * CELL_H);
  FONT_CHARS.split('').forEach((ch, i) => {
    const cx = (i % FONT_COLS) * CELL_W;
    const cy = Math.floor(i / FONT_COLS) * CELL_H;
    cv.mask(cx, cy, G[ch], [255, 255, 255], 255);
  });
  return { canvas: cv, rows };
}

